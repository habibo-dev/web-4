/** Deterministic agent routing for listings (kept in data so it can be
 *  overwritten per-property by the CMS later). */
export const listingAgents: Record<string, string> = {
  sale: "amine-belkacem",
  rent: "lina-hamidi",
  land: "sofiane-merabet",
  commercial: "sofiane-merabet",
  office: "sofiane-merabet",
};

export function agentForListing(property: Property): string {
  if (property.type === "land" || property.type === "commercial" || property.type === "office") {
    return listingAgents[property.type];
  }
  return listingAgents[property.transaction];
}
